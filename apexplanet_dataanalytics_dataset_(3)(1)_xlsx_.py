# Use the latest date in the dataset as the reference date
reference_date = data["Order_Date"].max() + pd.Timedelta(days=1)

rfm = data.groupby("Customer_ID").agg(
    Last_Purchase_Date=("Order_Date", "max"),
    Frequency=("Order_ID", "size"),
    Monetary=("Total_Sales", "sum"),
    Customer_Name=("Customer_Name", "first"),
    City=("City", "first"),
    Gender=("Gender", "first"),
    Age=("Age", "first")
).reset_index()

rfm["Recency_Days"] = (
    reference_date - rfm["Last_Purchase_Date"]
).dt.days

rfm = rfm[
    [
        "Customer_ID", "Customer_Name", "City", "Gender", "Age",
        "Last_Purchase_Date", "Recency_Days", "Frequency", "Monetary"
    ]
].copy()

print("RFM analysis completed.")
