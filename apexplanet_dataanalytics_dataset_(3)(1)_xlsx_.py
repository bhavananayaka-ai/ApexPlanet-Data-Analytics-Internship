def quintile_score(series, higher_is_better=True):
    """
    Rank first to handle ties, then divide customers into five groups.
    Returns scores from 1 to 5.
    """
    percentile_rank = series.rank(method="first", pct=True)

    scores = np.ceil(percentile_rank * 5).clip(1, 5).astype(int)

    if not higher_is_better:
        scores = 6 - scores

    return scores

# Lower recency in days is better, so reverse the score
rfm["R_Score"] = quintile_score(
    rfm["Recency_Days"], higher_is_better=False
)

rfm["F_Score"] = quintile_score(
    rfm["Frequency"], higher_is_better=True
)

rfm["M_Score"] = quintile_score(
    rfm["Monetary"], higher_is_better=True
)

rfm["RFM_Score"] = (
    rfm["R_Score"] + rfm["F_Score"] + rfm["M_Score"]
)

def assign_segment(row):
    r = row["R_Score"]
    f = row["F_Score"]
    m = row["M_Score"]

    if r >= 4 and f >= 4 and m >= 4:
        return "Champions"
    elif r >= 3 and f >= 3:
        return "Loyal Customers"
    elif r >= 4 and f <= 2:
        return "Recent Customers"
    elif r <= 2 and f >= 3:
        return "At Risk"
    elif r <= 2 and f <= 2:
        return "Needs Attention"
    else:
        return "Potential Loyalists"

rfm["Customer_Segment"] = rfm.apply(assign_segment, axis=1)

print("Customer segmentation completed.")
display(rfm["Customer_Segment"].value_counts().to_frame("Customer_Count"))

